def apply(root: Path, dry_run: bool = False) -> dict[str, str]:
    patches = {
        DB: patch_data, SERVICE: patch_service, TRAIN: patch_training,
        API_TEST: patch_api_test, OBS_TEST: patch_observability_test,
    }
    outputs: dict[str, str] = {}
    for relative, transform in patches.items():
        path = root / relative
        if not path.is_file():
            raise RuntimeError(f"Missing upstream file: {relative}")
        original = path.read_text(encoding="utf-8")
        modified = transform(original)
        ast.parse(modified, filename=str(relative))
        outputs[str(relative)] = modified
    if not dry_run:
        # Validate *all* files first, then write; do not partially patch on a
        # source-layout mismatch.
        for name, modified in outputs.items():
            path = root / name
            if path.read_text(encoding="utf-8") != modified:
                path.write_text(modified, encoding="utf-8")
                print(f"patched {name}")
            else:
                print(f"unchanged {name}")
    return outputs


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path("."))
    parser.add_argument("--check", action="store_true", help="validate without modifying files")
    args = parser.parse_args()
    apply(args.root, dry_run=args.check)
    print("Feature lineage patch checks passed.")


if __name__ == "__main__":
    main()
