def replace_once(source: str, old: str, new: str, description: str) -> str:
    count = source.count(old)
    if count != 1:
        raise RuntimeError(f"Unsupported source layout: {description} (expected 1 match, got {count})")
    return source.replace(old, new, 1)


def patch_data(source: str) -> str:
    if "CREATE TABLE IF NOT EXISTS prediction_feature_observations (" in source:
        if "_feature_observation" not in source:
            raise RuntimeError("Feature observation schema exists but persistence hook is missing")
        return source

    schema_anchor = '''    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
"""'''
    schema = '''    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Only fresh computations create observations; retries with an existing
-- request_id return the original prediction without recording a new snapshot.
CREATE TABLE IF NOT EXISTS prediction_feature_observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_request_id VARCHAR(128) NOT NULL REFERENCES predictions(request_id),
    order_id VARCHAR(128) NOT NULL REFERENCES orders(order_id),
    model_version VARCHAR(128) NOT NULL,
    feature_as_of TIMESTAMPTZ NOT NULL,
    feature_contract_sha256 CHAR(64) NOT NULL,
    contract_identity_source VARCHAR(64) NOT NULL,
    feature_hash CHAR(64) NOT NULL,
    features_jsonb JSONB NOT NULL,
    observed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_observation_per_distinct_snapshot
        UNIQUE (order_id, model_version, feature_contract_sha256, feature_hash)
);
CREATE INDEX IF NOT EXISTS idx_feature_observations_window
    ON prediction_feature_observations (model_version, observed_at, order_id);
"""'''
    source = replace_once(source, schema_anchor, schema, "predictions schema ending")
    # AppState.startup()/readyz already ensure schema once. Replaying all CREATE
    # TABLE/INDEX statements on every request would hurt the 10 RPS contract.
    source = replace_once(
        source,
        '''    raw_conn = _get_raw_conn(connection)
    init_db(raw_conn)

    with raw_conn.cursor() as cur:
        cur.execute(
            "SELECT order_id, risk_probability, model_version FROM predictions WHERE request_id = %s",
''',
        '''    raw_conn = _get_raw_conn(connection)
    # Schema must be initialized by AppState.startup/readyz or the ingestion
    # migration path, not as an implicit DDL side-effect of each prediction.

    with raw_conn.cursor() as cur:
        cur.execute(
            "SELECT order_id, risk_probability, model_version FROM predictions WHERE request_id = %s",
''',
        "remove per-request schema DDL",
    )

    anchor = '''    result = compute_fn()
    risk_prob = float(result["risk_probability"])
    model_ver = str(result["model_version"])
'''
    extra = '''    result = compute_fn()
    risk_prob = float(result["risk_probability"])
    model_ver = str(result["model_version"])
    # Internal-only metadata is never included in public PredictionResponse.
    feature_observation = result.get("_feature_observation")
'''
    source = replace_once(source, anchor, extra, "prediction metadata capture")

    old = '''                ON CONFLICT (request_id) DO NOTHING
                """,
                (request_id, order_id, risk_prob, model_ver),
            )
        raw_conn.commit()
'''
    new = '''                ON CONFLICT (request_id) DO NOTHING
                """,
                (request_id, order_id, risk_prob, model_ver),
            )
            # rowcount is 0 for an idempotency race: never persist metadata from
            # the losing computation, whose prediction was not committed.
            inserted = cur.rowcount == 1
            if inserted and feature_observation is not None:
                snapshot = feature_observation
                if not isinstance(snapshot, dict) or not isinstance(snapshot.get("features"), dict):
                    raise ValueError("Malformed private feature observation")
                cur.execute(
                    """
                    INSERT INTO prediction_feature_observations (
                        first_request_id, order_id, model_version,
                        feature_as_of, feature_contract_sha256,
                        contract_identity_source, feature_hash, features_jsonb
                    ) VALUES (%s, %s, %s, %s::timestamptz, %s, %s, %s, %s::jsonb)
                    ON CONFLICT (order_id, model_version,
                                 feature_contract_sha256, feature_hash) DO NOTHING
                    """,
                    (
                        request_id, order_id, model_ver,
                        snapshot["feature_as_of"],
                        snapshot["feature_contract_sha256"],
                        snapshot["contract_identity_source"],
                        snapshot["feature_hash"],
                        json.dumps(snapshot["features"], sort_keys=True,
                                   separators=(",", ":"), ensure_ascii=False, allow_nan=False),
                    ),
                )
        # The prediction and its first feature observation commit atomically.
        raw_conn.commit()
'''
    source = replace_once(source, old, new, "atomic prediction and observation insert")
    return source


def patch_service(source: str) -> str:
    if "from promiseops.feature_lineage import observation" in source:
        return source
    source = replace_once(
        source,
        "from promiseops.data import FEATURE_COLUMNS, build_features, get_or_save_prediction\n",
        "from promiseops.data import FEATURE_COLUMNS, build_features, get_or_save_prediction\n"
        "from promiseops.feature_lineage import observation\n",
        "service lineage import",
    )
    source = replace_once(
        source,
        '''    frame = build_features(conn, [order_id], as_of=datetime.now(UTC))
''',
        '''    # Preserve the same point-in-time cutoff for extraction and evidence.
    # AppState.startup already initializes schema: never run DDL per request.
    feature_as_of = datetime.now(UTC)
    frame = build_features(conn, [order_id], as_of=feature_as_of, ensure_schema=False)
''',
        "feature_as_of capture",
    )
    source = replace_once(
        source,
        '''        "model_version": str(release["model_version"]),
    }
''',
        '''        "model_version": str(release["model_version"]),
        "_feature_observation": observation(
            features, feature_as_of=feature_as_of, release=release
        ),
    }
''',
        "private serving observation",
    )
    return source


