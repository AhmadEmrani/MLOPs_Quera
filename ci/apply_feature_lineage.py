#!/usr/bin/env python3
"""Idempotent, guarded source edits for PromiseOps feature lineage persistence.

Extract the package over the repository root, then run this script. This does
NOT connect to production, MLflow, or GitLab. It refuses an unexpected source
layout instead of silently corrupting application code.
"""
